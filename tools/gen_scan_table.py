#!/usr/bin/env python3
"""Regenerate components/dryer_link/erd_scan_table.h, the list of data-point codes the full scan asks for.

Sources, both from https://github.com/mguaylam/esphome-gea (pinned at ef16751):
  erd-definitions/appliance_api_erd_definitions.json   GE Appliances' public ERD definitions (BSD 3-Clause)
  components/gea/gea2_erds_fork.txt                    codes seen on real appliances but not in GE's file (MIT)
Only the code numbers are taken, not names or descriptions.

Plus four codes that GE's own interface documents for its older "Hawk" and "Viper" dryers list and that neither
source above contains: 0x2003 cycle count, 0x2004 service error codes, 0x2005 and 0x200F demand response.

Usage: gen_scan_table.py <path to an esphome-gea checkout with its erd-definitions submodule>
"""
import json
import sys
from pathlib import Path

src = Path(sys.argv[1])
codes = set()
for erd in json.loads((src / "erd-definitions" / "appliance_api_erd_definitions.json").read_text())["erds"]:
    try:
        n = int(erd["id"], 16)
    except (KeyError, ValueError):
        continue
    if n <= 0xFFFF:
        codes.add(n)
for line in (src / "components" / "gea" / "gea2_erds_fork.txt").read_text().splitlines():
    line = line.strip()
    if line.lower().startswith("0x"):
        try:
            codes.add(int(line, 16))
        except ValueError:
            pass
codes |= {0x2003, 0x2004, 0x2005, 0x200F}  # GE "Maker Module - Hawk/Viper Dryer Interface Definition"
codes = sorted(codes)
out = [
    "// Generated by tools/gen_scan_table.py. Do not edit.",
    "// Code numbers from GE Appliances' public ERD definitions (BSD 3-Clause, (c) 2024 GE Appliances) and from",
    "// mguaylam/esphome-gea's gea2_erds_fork.txt (MIT, (c) 2024 mguaylam), both at esphome-gea ef16751, plus four",
    "// codes from GE's interface documents for its older dryers.",
    "#pragma once",
    "#include <cstddef>",
    "#include <cstdint>",
    "",
    "namespace esphome {",
    "namespace dryer_link {",
    "",
    "// Sorted ascending. The quick check uses the laundry block (0x2000-0x2FFF); the full scan uses all of it.",
    "static const uint16_t ERD_SCAN_TABLE[] = {",
]
for i in range(0, len(codes), 12):
    out.append("    " + ", ".join(f"0x{c:04X}" for c in codes[i : i + 12]) + ",")
out += [
    "};",
    f"static const size_t ERD_SCAN_TABLE_SIZE = {len(codes)};",
    "",
    "}  // namespace dryer_link",
    "}  // namespace esphome",
    "",
]
dest = Path(__file__).resolve().parent.parent / "components" / "dryer_link" / "erd_scan_table.h"
dest.write_text("\n".join(out))
laundry = [c for c in codes if 0x2000 <= c <= 0x2FFF]
print(f"{len(codes)} codes, {len(laundry)} in the laundry block 0x2000-0x2FFF -> {dest}")
